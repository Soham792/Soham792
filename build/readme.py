from lib import ROOT, esc

def write(cfg):
    u, br = cfg["username"], cfg["branch"]
    raw = f"https://raw.githubusercontent.com/{u}/{u}/{br}"
    img = lambda path, alt: f'<img src="{raw}/{path}?v=1" alt="{esc(alt)}" width="100%"/>'
    rows = "\n".join(f'| [**{p["name"]}**]({p["url"]}) | {p["desc"]} | `{p["stack"]}` |' for p in cfg["projects"])
    links = " &nbsp;·&nbsp; ".join(f'[{l["label"]}]({l["url"]})' for l in cfg["links"])
    md = f'''<div align="center">

{img("assets/hero.svg", f"{cfg['name']} - {cfg['role']}")}

{img("assets/about-life.svg", "About me: capabilities and hobbies")}

{img("assets/stack.svg", "Tech stack orbiting a glowing core, with grouped skill chips")}

{img("assets/id-dashboard.svg", "Lanyard ID badge and GitHub dashboard")}

</div>

## 🌃 Contributions, as a night-view city

<div align="center">

<img src="{raw}/profile-3d-contrib/profile-night-view.svg?v=1" alt="3D contribution city, refreshed daily" width="100%"/>

</div>

> The city above is generated by [`yoshi389111/github-profile-3d-contrib`](https://github.com/yoshi389111/github-profile-3d-contrib) via `.github/workflows/profile-3d.yml` and refreshed daily. Run the workflow once (Actions tab → *GitHub-Profile-3D-Contrib* → *Run workflow*) to create the first image.

## 🚀 Projects

| Project | What it is | Stack |
| :-- | :-- | :-- |
{rows}

## 🤝 Connect

<div align="center">

<a href="https://github.com/{u}">{img("assets/connect.svg", "Links: GitHub, LinkedIn, X, email")}</a>

{links}

</div>
'''
    out = ROOT.parent / "README.md"
    out.write_text(md, encoding="utf-8")
    wf = ROOT.parent / ".github" / "workflows" / "profile-3d.yml"
    wf.parent.mkdir(parents=True, exist_ok=True)
    wf.write_text('''name: GitHub-Profile-3D-Contrib

on:
  schedule: # daily at 18:00 UTC
    - cron: "0 18 * * *"
  workflow_dispatch:

permissions:
  contents: write

jobs:
  build:
    runs-on: ubuntu-latest
    name: generate-github-profile-3d-contrib
    steps:
      - uses: actions/checkout@v5
      - uses: yoshi389111/github-profile-3d-contrib@latest
        env:
          GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}
          USERNAME: ${{ github.repository_owner }}
      - name: Commit & Push
        run: |
          git config user.name github-actions
          git config user.email github-actions@github.com
          git add -A .
          if git commit -m "generated"; then
            git push
          fi
''')
    print("README.md + workflow written")
